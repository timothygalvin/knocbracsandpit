#!/usr/bin/env python3
"""Turn a submitted diagnostic into a re-marking worksheet for the senior agent.

A language diagnostic's auto-marking can only confirm what an accept list
anticipated. Everything else comes back "review" — which is where the whole
signal lives. This pulls those parts out next to the question that asked
them and the accept list that failed to judge them, so the senior agent
(Fable) can re-mark by MEANING, which is Step 1 of every language rubric in
docs/plans/.

    python3 tools/extract_review.py vozvrat
    python3 tools/extract_review.py gracees --result path/or/url.json

With no --result it picks the newest matching file from the live family
folder. Writes docs/results/<course>-diag-review.md.

THE VERDICTS ARE NOT THE LEARNER'S TO FILL IN. Self-marking a language test
is unreliable in itself, and worse, the rubrics cross-reference the
learner's self-report AGAINST the measurement — where those two disagree is
the most useful result in the file. Mixing them destroys the comparison.
"""
import sys, os, re, json, io, urllib.request, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEARN = os.path.join(ROOT, "sites", "knocbrac", "learn")
LIVE = "http://www.knocbrac.com/learn/results/"

def say(m): print(m, flush=True)

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "extract_review/1"})
    with urllib.request.urlopen(req, timeout=40) as r:
        return r.read().decode("utf-8", "replace")

def newest_result(course):
    idx = fetch(LIVE + "index.html")
    files = sorted(set(re.findall(r'href="([^"]+\.json)"', idx)), reverse=True)
    for f in files:
        if f.startswith(course + "-"):
            return LIVE + f
    raise SystemExit("no result file for course %r in the family folder" % course)

def load(path_or_url):
    if path_or_url.startswith(("http://", "https://")):
        return json.loads(fetch(path_or_url)), path_or_url
    with open(path_or_url, encoding="utf-8") as fh:
        return json.load(fh), path_or_url

def find_assessment(course, session_id):
    """The checkpoint doc the result came from."""
    for cand in (session_id, "diag", "cp1"):
        p = os.path.join(LEARN, course, "content", "%s.json" % cand)
        if os.path.exists(p):
            return json.load(open(p, encoding="utf-8")), p
    raise SystemExit("cannot find the assessment doc for %s/%s" % (course, session_id))

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        raise SystemExit("usage: extract_review.py <course> [--result <path|url>]")
    course = args[0]
    given = [a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--result=")]
    if "--result" in sys.argv[1:]:
        given = [sys.argv[sys.argv.index("--result") + 1]]
    src = given[0] if given else newest_result(course)
    res, src_label = load(src)
    doc, doc_path = find_assessment(course, res.get("session", ""))

    qmap, secof = {}, {}
    for s in doc.get("sections", []):
        for q in s["questions"]:
            qmap[q["id"]] = q
            secof[q["id"]] = s.get("name", s.get("id", ""))
    pmap = {(q["id"], p["id"]): p for q in qmap.values() for p in q["parts"]}

    rows, tally = [], collections.Counter()
    for qd in res.get("detail", []):
        for p in qd.get("parts", []):
            tally[p.get("mark", "?")] += 1
            if p.get("mark") in ("review", "blank"):
                sp = pmap.get((qd["q"], p["part"]), {})
                rows.append(dict(q=qd["q"], part=p["part"], level=qd.get("level"),
                                 sec=secof.get(qd["q"], ""), label=sp.get("label", ""),
                                 raw=p.get("raw", ""), accept=sp.get("accept"),
                                 mark=p.get("mark"),
                                 bydesign=(sp.get("type") == "text" and not sp.get("accept"))))
    bydesign = [r for r in rows if r["bydesign"]]
    unjudged = [r for r in rows if not r["bydesign"]]
    blanks = [r for r in rows if r["mark"] == "blank"]

    out = io.StringIO(); w = out.write
    w("# %s — diagnostic re-marking worksheet\n\n" % res.get("title", course))
    w("> **FOR THE SENIOR AGENT (Fable). Timothy does NOT fill these in.**\n")
    w("> Self-marking a language test is unreliable, and the rubric\n")
    w("> deliberately cross-references his self-report against the\n")
    w("> measurement — where the two disagree is the most informative\n")
    w("> result in the file. Mixing them destroys that comparison. The only\n")
    w("> things to ask him are the ones the rubric names as escalations.\n>\n")
    w("> Source: `%s`\n" % os.path.basename(src_label))
    w("> Assessment: `%s` · sat %s · student %s\n" %
      (os.path.relpath(doc_path, ROOT), (res.get("when") or "?")[:10], res.get("student", "?")))
    w("> Generated by `tools/extract_review.py` — regenerate freely; your\n")
    w("> verdicts are the thing worth preserving, so record them here.\n\n")
    w("## Marks as the engine left them\n\n")
    for k in ("correct", "incorrect", "review", "blank", "skipped"):
        if tally.get(k):
            w("- %s: **%d**\n" % (k, tally[k]))
    w("\n- of the non-correct: **%d** designed free production, "
      "**%d** the accept list could not judge, **%d** blank\n\n"
      % (len(bydesign), len(unjudged), len(blanks)))
    if not tally.get("incorrect"):
        w("Note: **zero parts came back `incorrect`** — nothing auto-markable was\n"
          "wrong. So the entire signal is in the items below.\n\n")
    w("Verdict vocabulary (per rubric Step 1): **right** · **wrong-form** ·\n"
      "**right-form-misspelled** (a typo in an otherwise correct form is a\n"
      "typing problem, not a grammar problem — count it grammatically right\n"
      "and note it separately).\n\n")

    for title, group, note in (
        ("Accept list could not judge — RE-MARK THESE FIRST", unjudged,
         "These are the ones that move the band line. Do them before any planning."),
        ("Designed free production — judge against the rubric", bydesign,
         "Written production and self-report. Never auto-markable by design.")):
        if not group:
            continue
        w("## %s\n\n%s\n\n" % (title, note))
        cur = None
        for r in sorted(group, key=lambda x: (x["sec"], x["q"], x["part"])):
            if r["sec"] != cur:
                cur = r["sec"]; w("### %s\n\n" % cur)
            w("**%s.%s** · level %s · engine said `%s`\n\n" %
              (r["q"], r["part"], r["level"], r["mark"]))
            w("- asked: %s\n" % (r["label"] or "(see the prompt in the assessment)"))
            w("- he wrote: `%s`\n" % (r["raw"] if str(r["raw"]).strip() else "(left blank)"))
            if r["accept"] is not None:
                a = r["accept"]
                w("- accept list held: %s%s\n"
                  % (", ".join("`%s`" % x for x in a[:6]),
                     " … (%d total)" % len(a) if len(a) > 6 else ""))
            w("- **verdict (Fable):** \n- **note:** \n\n")

    dest = os.path.join(ROOT, "docs", "results", "%s-diag-review.md" % course)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    open(dest, "w", encoding="utf-8").write(out.getvalue())
    say("wrote %s" % os.path.relpath(dest, ROOT))
    say("  marks: %s" % dict(tally))
    say("  to re-mark: %d (plus %d designed production, %d blank)"
        % (len(unjudged), len(bydesign), len(blanks)))

if __name__ == "__main__":
    main()
